function r = load_run(runDir)
%LOAD_RUN  Load one DUNE dataset run.
%
%   r = load_run('runs/run_01_20260725_184427')
%
%   r.uwb.R      A x S ranges in metres, NaN where no measurement
%   r.uwb.gap    A x S  RX - FP in dB, the NLOS indicator
%   r.gt.pos     3 x N  ground-truth position in metres
%   r.meta       the run's metadata.json
%
%   run.mat is MATLAB v7.3, so plain LOAD works here.
%
%   NOTE: the AprilTag and UWB frames are logged raw. Fit an SE(2) transform
%   before comparing estimates against r.gt.pos — see docs/coordinate_frames.md.

    arguments
        runDir (1,:) char
    end

    matFile = fullfile(runDir, 'run.mat');
    assert(isfile(matFile), 'No run.mat in %s', runDir);
    S = load(matFile);

    r.meta = jsondecode(fileread(fullfile(runDir, 'metadata.json')));

    u = S.data.uwb;
    R = double(u.R);
    R(R <= 0) = NaN;
    r.uwb = struct( ...
        'anchor_ids', double(u.anchorIds(:)), ...
        'R',          R, ...
        'RX',         double(u.RX), ...
        'FP',         double(u.FP), ...
        'gap',        double(u.RX) - double(u.FP), ...
        'tag',        double(u.tag(:))', ...
        't_rel',      double(u.t_rel(:))', ...
        't_posix',    double(u.t_posix(:))', ...
        'quat',       double(u.quat), ...
        'acc',        double(u.acc), ...
        'gyro',       double(u.gyro));

    r.gt = struct( ...
        'pos',     double(S.data.apriltag_pos), ...
        'euler',   double(S.data.apriltag_euler), ...
        't_posix', double(S.data.t_posix(:))', ...
        't_rel',   double(S.data.time(:))');

    r.ctrl = struct( ...
        'imu_euler',           double(S.data.imu_euler), ...
        'imu_accel',           double(S.data.imu_accel), ...
        'imu_gyro',            double(S.data.imu_gyro), ...
        'wheel_rpm',           double(S.data.wheel_rpm), ...
        'motor_rpm',           double(S.data.motor_rpm), ...
        'commanded_motor_rpm', double(S.data.commanded_motor_rpm), ...
        'steering_angles',     double(S.data.steering_angles), ...
        'V_cmd',               double(S.data.V_cmd(:))', ...
        'omega_cmd',           double(S.data.omega_cmd(:))', ...
        'segment_id',          double(S.data.segment_id(:))');

    m = S.metadata;
    r.rover = struct( ...
        'wheelbase_m',          double(m.wheelbase), ...
        'track_width_m',        double(m.track_width), ...
        'wheel_radius_m',       double(m.wheel_radius), ...
        'control_rate_hz',      double(m.control_rate), ...
        'anchors_layout',       char(m.uwb.anchors_layout(:)'), ...
        'front_tag',            double(m.uwb.frontTag), ...
        'rear_tag',             double(m.uwb.rearTag), ...
        'baseline_m',           double(m.uwb.baseline_m), ...
        'apriltag_offset_body', double(m.uwb.apriltag_offset_body(:))', ...
        'frame_note',           char(m.uwb.frame_note(:)'));

    if nargout == 0
        fprintf('%s   %.1f s   %.2f m driven\n', r.meta.run_id, ...
                r.meta.duration_s, r.meta.path_length_m);
        fprintf('  layout   %s\n', r.rover.anchors_layout);
        fprintf('  anchors  %s\n', mat2str(r.uwb.anchor_ids'));
        fprintf('  sweeps   %d  (%.2f anchors/sweep)\n', size(r.uwb.R, 2), ...
                r.meta.mean_anchors_per_sweep);
        fprintf('  ranges   %.2f .. %.2f m\n', min(r.uwb.R, [], 'all'), ...
                max(r.uwb.R, [], 'all'));
        fprintf('\n  NOTE: %s\n', r.rover.frame_note);
        clear r
    end
end
